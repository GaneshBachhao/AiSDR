"""
Integration-level regression test: solutions generated by
CreateRecommendationHandler must actually survive a save/reload cycle
against a real DB -- exercised against a real in-memory DB, a real
SqlAlchemyUnitOfWork, and the real SqlAlchemy repositories (not mocks).
Before this sprint, RecommendationModel had no column to persist
solutions at all, so this is the concrete proof that gap is closed.
"""

from __future__ import annotations

import json
from unittest.mock import AsyncMock

import pytest

from app.application.recommendation.commands.create_recommendation import (
    CreateRecommendationCommand,
)
from app.application.recommendation.handlers.create_recommendation_handler import (
    CreateRecommendationHandler,
)
from app.domain.ai.entities.ai_response import AIResponse
from app.domain.ai.enums.finish_reason import FinishReason
from app.domain.assessment.entities.assessment import Assessment
from app.domain.discovery.identifiers.discovery_id import DiscoveryId
from app.infrastructure.persistence.repositories.assessment.sqlalchemy_assessment_repository import (
    SqlAlchemyAssessmentRepository,
)
from app.infrastructure.persistence.unit_of_work.sqlalchemy_unit_of_work import (
    SqlAlchemyUnitOfWork,
)


@pytest.mark.asyncio
async def test_generated_solutions_survive_a_real_save_and_reload(async_session):
    assessment = Assessment(
        discovery_id=DiscoveryId(),
        summary="Manual monthly reporting across disconnected spreadsheets.",
        weaknesses="No integration between finance systems.",
    )
    assessment_repo = SqlAlchemyAssessmentRepository(async_session)
    await assessment_repo.add(assessment)
    await async_session.commit()

    uow = SqlAlchemyUnitOfWork(session=async_session)
    ai_service = AsyncMock()
    ai_service.execute.return_value = AIResponse(
        content=json.dumps(
            [
                {
                    "title": "Business Process Automation",
                    "description": "Automate monthly reporting.",
                    "solution_type": "Automation",
                    "priority": "High",
                    "is_existing_offering": True,
                }
            ]
        ),
        finish_reason=FinishReason.STOP,
    )

    handler = CreateRecommendationHandler(uow, ai_service)
    created = await handler.handle(
        CreateRecommendationCommand(assessment_id=assessment.id.value)
    )
    assert len(created.solutions) == 1

    # Fresh repository read (simulates a completely separate GET request) --
    # proves the solution round-trips through the DB, not just in-memory.
    from app.domain.recommendation.identifiers.recommendation_id import RecommendationId

    reload_repo = SqlAlchemyUnitOfWork(session=async_session).recommendation_repository
    reloaded = await reload_repo.get_by_id(RecommendationId(created.id))

    assert reloaded is not None
    assert len(reloaded.solutions) == 1
    assert reloaded.solutions[0].title == "Business Process Automation"
    assert reloaded.solutions[0].is_existing_offering is True
    assert reloaded.solutions[0].solution_type.value == "Automation"


@pytest.mark.asyncio
async def test_calling_create_twice_for_the_same_assessment_is_idempotent(async_session):
    assessment = Assessment(
        discovery_id=DiscoveryId(),
        summary="Manual monthly reporting across disconnected spreadsheets.",
    )
    assessment_repo = SqlAlchemyAssessmentRepository(async_session)
    await assessment_repo.add(assessment)
    await async_session.commit()

    uow = SqlAlchemyUnitOfWork(session=async_session)
    ai_service = AsyncMock()
    ai_service.execute.return_value = AIResponse(
        content=json.dumps(
            [{"title": "AI Consulting", "description": "x", "solution_type": "AI Agent",
              "priority": "Medium", "is_existing_offering": True}]
        ),
        finish_reason=FinishReason.STOP,
    )
    handler = CreateRecommendationHandler(uow, ai_service)

    first = await handler.handle(CreateRecommendationCommand(assessment_id=assessment.id.value))
    second = await handler.handle(CreateRecommendationCommand(assessment_id=assessment.id.value))

    assert first.id == second.id
    ai_service.execute.assert_awaited_once()  # second call short-circuited before generating again
